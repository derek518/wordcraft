-- 第二词性。
--
-- 47% 的词有两种以上词性，教学区间（rank 600–5000）里有 1599 个实词如此。
-- 单列一个 `pos` 意味着 `watch` 只教「看」不教「手表」、`train` 只教「火车」
-- 不教「训练」、`right` 只教「正确的」不教「权利」——这些都是高考高频考点。
--
-- 为什么另存两列，而不是拼进 `meaning`：
--
-- 拼在一起会毁掉四选一。只有部分词有第二词性，正确答案就成了唯一那个
-- 「长选项」，不认识单词也能选对。干扰项按同词性挑，补不齐这个结构。
--
-- 所以出题仍然只考主词性（选项长度一致），第二词性在揭晓时补充展示——
-- 考一个义项，教两个。
--
-- 可空：多数词没有同样常用的第二词性，`NULL` 就是「没有」，
-- 不用空串伪装成有。

ALTER TABLE words ADD COLUMN pos_2 TEXT;
ALTER TABLE words ADD COLUMN meaning_2 TEXT;
